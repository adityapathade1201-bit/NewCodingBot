import numpy as np

def array_operations(A, B):
    # Convert A and B to Numpy arrays
    A = np.array(A)
    B = np.array(B)

    # Arithmetic Operations
    sum_result = A + B
    diff_result = A - B
    prod_result = A * B

    # Statistical Operations
    mean_A = np.mean(A)
    median_A = np.median(A)
    std_dev_A = np.std(A)

    # Bitwise Operations
    and_result = A & B
    or_result = A | B
    xor_result = A ^ B

    return {
        "arithmetic": (sum_result, diff_result, prod_result),
        "stats": (mean_A, median_A, std_dev_A),
        "bitwise": (and_result, or_result, xor_result)
    }

