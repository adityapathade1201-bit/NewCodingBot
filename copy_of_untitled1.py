import numpy as np

def get_3x3_array(name):
    print(f"Enter the elements for {name} (3 rows, 3 space-separated integers per row):")
    elements = []
    for i in range(3):
        row = list(map(int, input().split()))
        elements.append(row)
    return np.array(elements)

# 1. Input Format: Prompt user for two 3x3 arrays
